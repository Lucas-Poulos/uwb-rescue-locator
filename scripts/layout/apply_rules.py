#!/usr/bin/env python3
"""Write the routing rules into bay-station.kicad_pro (netclasses + wildcard
patterns + fab minimums) and bay-station.kicad_dru (conditioned rules).

Edits the JSON directly and keeps every other key byte-for-byte: the file
round-trips through json.dumps(indent=2) unchanged, so the diff is only what
this script adds.  Idempotent.  Never goes through pcbnew BOARD.Save(), which
wipes the .kicad_pro netclasses.

    python3 scripts/layout/apply_rules.py [--project bay-station/bay-station]

Source of truth: scripts/layout/hs_nets.json.
"""
import argparse
import copy
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))


def load_spec():
    with open(os.path.join(HERE, "hs_nets.json")) as f:
        return json.load(f)


def netclass_patterns(spec):
    out = []
    for g in spec["groups"]:
        for pat in g.get("patterns", []):
            out.append({"netclass": g["class"], "pattern": pat})
    return out


def apply_pro(path, spec):
    with open(path) as f:
        pro = json.load(f)
    ns = pro["net_settings"]
    default = next(c for c in ns["classes"] if c["name"] == "Default")
    classes = [default]
    for name, c in spec["classes"].items():
        if name == "Default":
            default["track_width"] = c["track"]
            default["clearance"] = c["clearance"]
            default["via_diameter"] = c["via_dia"]
            default["via_drill"] = c["via_drill"]
            continue
        n = copy.deepcopy(default)
        n.update({"name": name, "track_width": c["track"], "clearance": c["clearance"],
                  "via_diameter": c["via_dia"], "via_drill": c["via_drill"],
                  "priority": c["priority"]})
        classes.append(n)
    ns["classes"] = classes
    ns["netclass_patterns"] = netclass_patterns(spec)

    fab = spec["fab"]
    r = pro["board"]["design_settings"]["rules"]
    r["min_track_width"] = fab["min_track_mm"]
    r["min_clearance"] = fab["min_space_mm"]
    r["min_via_diameter"] = fab["min_via_dia_mm"]
    r["min_through_hole_diameter"] = fab["min_via_drill_mm"]
    r["min_via_annular_width"] = fab["min_annular_mm"]
    r["min_hole_to_hole"] = fab["min_hole_to_hole_mm"]
    r["min_copper_edge_clearance"] = fab["min_edge_clearance_mm"]

    ds = pro["board"]["design_settings"]
    ds["track_widths"] = [0.0, 0.2, 0.3, 0.45, 0.5, 1.0]
    ds["via_dimensions"] = [{"diameter": 0.0, "drill": 0.0},
                            {"diameter": 0.6, "drill": 0.3},
                            {"diameter": spec["stitch_via"]["dia"], "drill": spec["stitch_via"]["drill"]},
                            {"diameter": 0.8, "drill": 0.4}]
    with open(path, "w") as f:
        f.write(json.dumps(pro, indent=2) + "\n")


def dru_text(spec):
    c = spec["classes"]
    rf, clk = c["RF50"], c["CLK"]
    L = ["(version 1)", "",
         "# bay-station custom rules.  GENERATED by scripts/layout/apply_rules.py from",
         "# scripts/layout/hs_nets.json -- edit there, not here.",
         "#",
         "# Every rule below is CONDITIONED.  An unconditioned clearance rule would",
         "# override every netclass clearance (kicad-pcbnew-headless-gotchas).",
         "# The RF50/CLK netclass clearance stays 0.15 mm because the DW3210 pad",
         "# pitch (0.4 mm, 0.25 mm pads) leaves exactly 0.15 mm; the wider keep-off",
         "# applies only track/via/zone-to-track/via/zone, never pad-to-pad.",
         ""]

    def rule(name, cond, *constraints, severity=None):
        L.append('(rule "%s"' % name)
        if severity:
            L.append("\t(severity %s)" % severity)
        L.append('\t(condition "%s")' % cond)
        for k in constraints:
            L.append("\t" + k)
        L.append(")")
        L.append("")

    rule("RF50 keep-off (track/via/zone to foreign track/via/zone)",
         "A.NetClass == 'RF50' && A.Type != 'Pad' && B.NetClass != 'RF50' && (B.Type == 'Track' || B.Type == 'Via' || B.Type == 'Zone')",
         "(constraint clearance (min %.2fmm))" % rf["dru_clearance_mm"])
    rule("RF50 width window (neck at the pad .. 0.5 mm)",
         "A.NetClass == 'RF50' && A.Type == 'Track'",
         "(constraint track_width (min %.2fmm) (max %.2fmm))" % (rf["dru_track_min"], rf["dru_track_max"]))
    rule("RF50 carries no vias",
         "A.NetClass == 'RF50' && A.Type == 'Via'",
         "(constraint disallow via)")
    rule("CLK keep-off from other tracks/vias/zones",
         "A.NetClass == 'CLK' && A.Type == 'Track' && B.NetClass != 'CLK' && (B.Type == 'Track' || B.Type == 'Via' || B.Type == 'Zone')",
         "(constraint clearance (min %.2fmm))" % clk["dru_clearance_mm"])
    # warnings only: 0.2 mm pad-escape stubs on power pads are deliberate and short
    rule("POWER_HI minimum track width (stubs excepted by eye)",
         "A.NetClass == 'POWER_HI' && A.Type == 'Track'",
         "(constraint track_width (min %.2fmm))" % c["POWER_HI"]["dru_track_min"], severity="warning")
    rule("POWER_MID minimum track width",
         "A.NetClass == 'POWER_MID' && A.Type == 'Track'",
         "(constraint track_width (min %.2fmm))" % c["POWER_MID"]["dru_track_min"], severity="warning")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", default=os.path.join(REPO, "bay-station", "bay-station"))
    a = ap.parse_args()
    spec = load_spec()
    apply_pro(a.project + ".kicad_pro", spec)
    with open(a.project + ".kicad_dru", "w") as f:
        f.write(dru_text(spec))
    print("wrote", a.project + ".kicad_pro", "and .kicad_dru;",
          len(spec["classes"]), "classes,", len(netclass_patterns(spec)), "patterns")


if __name__ == "__main__":
    main()
